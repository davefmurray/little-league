#!/usr/bin/env python3
"""P1: add the $07FC match index and heap-correct winner advance.

    python3 tools/build_match_index.py build/direct14.nes -o build/direct17.nes

The 63-slot bracket is a binary heap in PRG RAM:

    slots 0..31   first-round teams      ($7700-$771F)
    slots 32..62  winners               ($7720-$773E)

For match m (0..30), the pair is always slots 2m/2m+1 and the winner
always goes to slot 32+m.  That is because the source base of each round
is exactly 2*m: 0->0, 16->32, 24->48, 28->56, 30->60.  The old plan's
`$7720 + (m>>1)` is wrong for rounds 2+; the correct destination is
`$7720 + m`.

Patches (all in direct14):

  bank 11 $8360  A handler: pair = $7700[2*$07FC], $7700[2*$07FC+1]
  bank 11 $8380  initial entry: $07FC=0, slots 32..62 = $FF
  bank 11 $83A0  scene-0B hook: $7720[m] = pair[0]; INC $07FC
  fixed $FF53    initial entry JMP $8000 -> JMP $8380 (one-time init)
  fixed $FFE4    scene-0B  JMP $8000 -> JMP $83A0 (winner + advance)

The one-time init is deliberately on the $FF20 (scene-18 END) path, not
on $8000, because $8000 redraws the bracket after every game and must not
erase the winners or the match index.
"""
import argparse

HEADER = 16
PRG = 0x4000
BANK11 = 11
FIXED = 15


def bank_off(bank, addr):
    base = 0xC000 if bank == FIXED else 0x8000
    return HEADER + bank * PRG + (addr - base)


def patch(rom, bank, addr, expected, new, label):
    off = bank_off(bank, addr)
    old = bytes(rom[off:off + len(expected)])
    if old != expected:
        raise SystemExit(
            f"{label}: expected {expected.hex(' ')} at bank{bank} "
            f"${addr:04X}, found {old.hex(' ')}")
    rom[off:off + len(new)] = new
    print(f"bank{bank} ${addr:04X}: {label} ({len(new)} bytes)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rom", help="direct14.nes (P1 return-to-bracket build; this is the current binary base, not regenerated by this tool)")
    ap.add_argument("-o", "--out", default="build/direct17.nes")
    args = ap.parse_args()

    rom = bytearray(open(args.rom, "rb").read())
    if rom[4] <= FIXED:
        raise SystemExit(f"{args.rom}: {rom[4]} PRG banks, need 16")

    # A handler: pair by the live match index.
    pair = bytes([
        0xAD, 0xFC, 0x07,       # LDA $07FC
        0x0A,                   # ASL A
        0xAA,                   # TAX
        0xBD, 0x00, 0x77,       # LDA $7700,X
        0x8D, 0xFA, 0x07,       # STA $07FA
        0xBD, 0x01, 0x77,       # LDA $7701,X
        0x8D, 0xFB, 0x07,       # STA $07FB
        0x4C, 0x00, 0x83,       # JMP $8300  (launch stub)
    ])
    patch(rom, BANK11, 0x8360,
          bytes([0xAD, 0x00, 0x77, 0x8D, 0xFA, 0x07,
                 0xAD, 0x01, 0x77, 0x8D, 0xFB, 0x07,
                 0x4C, 0x00, 0x83]),
          pair, "pair by $07FC")

    # One-time bracket init, reached only from the scene-18 END hook.
    init = bytes([
        0xA9, 0x00,             # LDA #$00
        0x8D, 0xFC, 0x07,       # STA $07FC
        0xA9, 0xFF,             # LDA #$FF
        0xA2, 0x20,             # LDX #$20
        0x9D, 0x00, 0x77,       # STA $7700,X   ; slots 32..62
        0xE8,                   # INX
        0xE0, 0x3F,             # CPX #$3F
        0xD0, 0xF8,             # BNE $8389
        0x4C, 0x00, 0x80,       # JMP $8000
    ])
    patch(rom, BANK11, 0x8380, b"\xff" * len(init), init,
          "63-slot / $07FC init")

    # Scene-0B return: winner = first team of the match, slot 32+m.
    winner = bytes([
        0xAE, 0xFC, 0x07,       # LDX $07FC
        0xAD, 0xFC, 0x07,       # LDA $07FC
        0x0A,                   # ASL A
        0xA8,                   # TAY
        0xB9, 0x00, 0x77,       # LDA $7700,Y
        0x9D, 0x20, 0x77,       # STA $7720,X
        0xEE, 0xFC, 0x07,       # INC $07FC
        0x4C, 0x00, 0x80,       # JMP $8000
    ])
    patch(rom, BANK11, 0x83A0, b"\xff" * len(winner), winner,
          "winner write + advance")

    # direct14's scene-0B hook still writes $7700 to $7720 before switching
    # banks.  That stale pre-write would clobber match 0's winner after every
    # later game; the $8380 routine owns the write now.
    patch(rom, FIXED, 0xFFC0,
          bytes([0xAD, 0x00, 0x77, 0x8D, 0x20, 0x77]),
          b"\xea" * 6, "drop stale $7720 pre-write")

    # Initial scene-18 entry runs the one-time init before $8000.
    patch(rom, FIXED, 0xFF53,
          bytes([0x4C, 0x00, 0x80]), bytes([0x4C, 0x80, 0x83]),
          "END entry -> init")

    # Scene 0B runs the advance routine before the bracket redraw.
    patch(rom, FIXED, 0xFFE4,
          bytes([0x4C, 0x00, 0x80]), bytes([0x4C, 0xA0, 0x83]),
          "scene-0B -> advance")

    open(args.out, "wb").write(rom)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
